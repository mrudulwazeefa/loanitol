                    <li>Property Development or Construction: To finance the construction or redevelopment of commercial properties.</li>
                    <li>Collateral: The commercial property being purchased, refinanced, or constructed typically serves as collateral. This means that if the borrower defaults on the loan, the lender has the right to seize the property to recover the outstanding loan amount. </li>
