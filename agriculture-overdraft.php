            <div class="container">
                <h4 class="h4-size2">Overview</h4>
                <p>Agri OD is a type of short-term credit arrangement that banks and other financial institutions offer to farmers and agricultural enterprises. It enables the borrower to take out cash from the bank account up to a pre-approved limit in order to cover the operating expenses of their farming operations. The main purpose of the overdraft is to control changes in the agriculture industry's cash flow.</p>
                <ul>
                    <li><b>Hypothecation of Crops or Produce:</b> The borrower pledges the crops or produce as security.</li>
                    <li><b>Fixed Deposits or Bank Guarantees:</b> Some banks may also accept a fixed deposit or other guarantees from a reliable source as security. </li>
                    <li><b>Personal Guarantee:</b> In some cases, the personal guarantee of the borrower or a third party may be required.</li>
                    <li><b>Renewable:</b> The overdraft facility can be renewed annually or according to the agreed terms, based on the agricultural cycle.</li>
                </ul>
