                                    sector loans, particularly those operating in segments like SME lending and housing.
                                </li>
                                <li>Exemptions:  Certain categories of NBFCs regulated by other regulators are exempted
                                    from RBI registration requirements.</li>
                                <li>Net Owned Funds (NOF): RBI has raised the NOF requirement for NBFCs to strengthen
