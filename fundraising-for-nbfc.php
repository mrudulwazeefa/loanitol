                                <li>
                                    Exposure Limits:  Banks' exposure to NBFCs, particularly Infrastructure Finance
                                    Companies (IFCs), is subject to specific limits, such as not exceeding 15% of their
                                    capital funds.</li>
                                <li>Prudential Norms: Banks must follow prudential guidelines and exposure norms
                                    prescribed by the RBI when extending credit facilities to NBFCs.</li>
                                <li>Risk Weighting: The RBI has adjusted risk weights on bank loans to NBFCs, including
                                    those related to consumer microfinance loans, potentially encouraging banks to
                                    increase funding to NBFCs.</li>
                            </ol>
