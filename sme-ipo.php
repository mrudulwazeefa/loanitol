                    <h4 class="mb-4 h4-size2">BSE SME Eligibility Requirements</h4>
                    <ul class="mt-4">
                        <li>The company must be incorporated under the Companies Act, 1956.</li>
                        <li>The company should have a positive net worth.</li>
                        <li>The net tangible assets of the company should be ₹1.5 crore.</li>
                        <li>The company should have a track record of operations of a minimum of 3 years. If not, the
                            company should have been funded by banks/financial institutions/central government or state
                            government or the group company, which should be listed for a minimum of 2 years on either
                            the main board or SME board of BSE. It should have positive cash accruals (earnings before
                            depreciation and taxes) in any year of the last 3 years.</li>
                        <li>The company should have a website.</li>
                        <li>The company should facilitate trading in Demat form and also have an agreement with both
                            Indian depositories CDSL and NSDL.</li>
                        <li>The list of promoters should not have changed in the preceding year from the date of
                            applying to BSE for listing under the SME segment.</li>
                        <li>There are also additional criteria for microfinance companies and broking companies in BSE
                            SME.</li>
                    </ul>
